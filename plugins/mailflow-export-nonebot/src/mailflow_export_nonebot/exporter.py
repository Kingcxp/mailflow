"""Generate a NoneBot2 plugin that embeds a configured MailFlow instance.

The generated package is a standard ``nonebot-plugin-mailflow`` wheel: a
``pyproject.toml`` (declaring ``nonebot2`` plus every enabled MailFlow
plugin as dependencies), the plugin module registering driver
startup/shutdown hooks, and the resolved ``config.toml``. Installing it into
a NoneBot project (``NONEBOT_PLUGINS`` or ``load_plugin``) boots the MailFlow
service together with the bot.

Secrets note: the embedded config is the *resolved* live configuration. If it
contains real tokens, replace them with ``${ENV_VAR}`` placeholders in the
generated ``config.toml`` before committing the plugin anywhere.
"""

from __future__ import annotations

from mailflow.bot_export import BotExportContext, BotExportResult
from mailflow.config import write_config

PLUGIN_NAME = "nonebot-plugin-mailflow"
MODULE_NAME = "nonebot_plugin_mailflow"
FRAMEWORK = "nonebot"

_PYPROJECT = """[project]
name = "{name}"
version = "{version}"
description = "MailFlow engine embedded in NoneBot2 (generated by mailflow export)"
requires-python = ">=3.11"
dependencies = [
    "nonebot2>=2.0.0",
    "mailflow-core",
    "mailflow-bundled",
{deps}
]

[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[tool.hatch.build.targets.wheel]
packages = ["src/{module}"]
"""

_PLUGIN_INIT = '''"""MailFlow engine embedded as a NoneBot2 plugin (generated by mailflow export).

Install this package into a NoneBot2 project and load it (add it to
``NONEBOT_PLUGINS`` or call ``load_plugin``); the MailFlow service starts
with the bot and stops on shutdown. Configure it by editing
``config.toml`` next to this module.

Chat commands are prefixed with ``mailflow`` (``mailflow mail list``,
``mailflow help``) or ``/mailflow`` (``/mailflow help``) so they never
collide with other plugins\' commands. Long command replies
are split into separate messages.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from nonebot import get_driver, on_message, on_notice
from nonebot.adapters import Bot, Event

driver = get_driver()
_service: Any = None
_router: Any = None



@driver.on_startup
async def _start_mailflow() -> None:
    """Boot the MailFlow service and the command router when NoneBot starts."""
    global _service, _router
    if _service is not None:
        return
    from mailflow.commands import CommandRouter
    from mailflow.config import load_config
    from mailflow.service import start_service
    from mailflow_bundled import create_plugin_manager

    config = load_config(Path(__file__).resolve().parent / "config.toml")
    _service = await start_service(
        config, plugin_manager=create_plugin_manager(config), discover_plugins=False
    )
    _router = CommandRouter(_service)


@driver.on_shutdown
async def _stop_mailflow() -> None:
    """Stop the MailFlow service when NoneBot shuts down."""
    global _service, _router
    if _service is not None:
        await _service.stop()
        _service = None
        _router = None


_mailflow_matcher = on_message(priority=10, block=False)
_mailflow_file_matcher = on_notice(priority=10, block=False)


@_mailflow_file_matcher.handle()
async def _handle_mailflow_file(bot: Bot, event: Event) -> None:
    if _service is None or getattr(event, "notice_type", "") not in {"group_upload", "offline_file"}:
        return
    sender = str(getattr(event, "user_id", "") or "")
    group_id = str(getattr(event, "group_id", "") or "")
    context = _service.permission_context(sender=sender, provider=bot.adapter.get_name(), instance_id=str(bot.self_id), chat_id=group_id or sender)
    if not context.is_admin:
        return
    from mailflow.chat_files import framework_notice_files, receive_files
    from mailflow.errors import error_text
    from mailflow.permissions import permission_scope
    file = getattr(event, "file", None)
    identity = str(file.get("id", "") if isinstance(file, dict) else getattr(file, "id", ""))
    payload = {"text": "", "sender": sender, "provider": bot.adapter.get_name(), "instance_id": str(bot.self_id), "chat_id": group_id or sender, "request_id": identity}
    try:
        with permission_scope(context):
            payload["files"] = await framework_notice_files(event, bot)
            await receive_files(_service, payload)
        async for reply in _service.chat_command_stream(payload["text"], sender=sender, provider=bot.adapter.get_name(), instance_id=str(bot.self_id), chat_id=group_id or sender, request_id=identity):
            pages = _service.chat_reply_chunks(reply)
            for page in pages if isinstance(pages, list) else [pages]:
                if page:
                    await _service.pace_bot(bot.adapter.get_name(), str(bot.self_id))
                    await _mailflow_file_matcher.send(page)
    except Exception as exc:
        await _mailflow_file_matcher.send(error_text(exc, _service.t))


@_mailflow_matcher.handle()
async def _handle_mailflow(bot: Bot, event: Event) -> None:
    """Dispatch ``mailflow ...`` chat messages to the shared command router."""
    text = str(event.get_plaintext() or "").strip()
    if _router is None:
        return
    if text.partition(" ")[0] == "/mailflow":
        line = text[len("/mailflow"):].strip()
    elif text.startswith("mailflow "):
        line = text[len("mailflow "):].strip()
    else:
        line = None
    sender = str(event.get_user_id())
    group_id = str(getattr(event, "group_id", "") or "")
    mentioned = event.is_tome()
    if line is None and group_id and not mentioned:
        return
    from mailflow.chat_files import framework_files, receive_files, file_sender_scope, framework_send_file
    from mailflow.errors import error_text

    payload = {"text": text, "sender": sender, "provider": bot.adapter.get_name(), "instance_id": str(bot.self_id), "chat_id": group_id or sender, "request_id": str(getattr(event, "message_id", "") or "")}
    try:
        payload["files"] = await framework_files(getattr(event, "get_message", lambda: [])(), bot)
        await receive_files(_service, payload)
    except Exception as exc:
        await _mailflow_matcher.send(error_text(exc, _service.t))
        return
    async def send_managed(file):
        await framework_send_file(file, bot=bot, group_id=group_id, sender=sender)
    with file_sender_scope(send_managed):
        async for reply in _service.chat_command_stream(
            _service.command_prefix() + "mailflow " + line if line is not None else payload["text"],
            sender=sender,
            provider=bot.adapter.get_name(),
            instance_id=str(bot.self_id),
            chat_id=group_id or sender,
            chat_type="group" if group_id else "private",
            request_id=str(getattr(event, "message_id", "") or ""),
            mentioned=mentioned,
        ):
            pages = _service.chat_reply_chunks(reply)
            for page in pages if isinstance(pages, list) else [pages]:
                if page:
                    await _service.pace_bot(bot.adapter.get_name(), str(bot.self_id))
                    await _mailflow_matcher.send(page)


'''

