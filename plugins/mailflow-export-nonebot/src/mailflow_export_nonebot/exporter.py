def export_nonebot(context: BotExportContext) -> BotExportResult:
    """Write the NoneBot2 plugin package under ``context.output_dir``."""
    output = context.output_dir
    output.mkdir(parents=True, exist_ok=True)
    version = context.version or "0.1.0"
    deps = "\n".join(f'    "{pid}",' for pid in sorted(set(context.plugin_ids)))
    (output / "pyproject.toml").write_text(
        _PYPROJECT.format(
            name=PLUGIN_NAME,
            version=version,
            module=MODULE_NAME,
            deps=deps,
        ),
        encoding="utf-8",
    )
    (output / "README.md").write_text(
        _README.format(name=PLUGIN_NAME, module=MODULE_NAME), encoding="utf-8"
    )
    module_dir = output / "src" / MODULE_NAME
    module_dir.mkdir(parents=True, exist_ok=True)
    (module_dir / "__init__.py").write_text(_PLUGIN_INIT, encoding="utf-8")
    write_config(context.config, module_dir / "config.toml")
    created = [
        "pyproject.toml",
        "README.md",
        f"src/{MODULE_NAME}/__init__.py",
        f"src/{MODULE_NAME}/config.toml",
    ]
    return BotExportResult(
        framework=FRAMEWORK,
        plugin_name=PLUGIN_NAME,
        created=created,
        notes=(
            "The exported config.toml contains the resolved live configuration; "
            "replace real secrets with ${ENV_VAR} placeholders before sharing."
        ),
    )


